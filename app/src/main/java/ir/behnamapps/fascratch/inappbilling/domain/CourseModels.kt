data class Course(val id: String, val title: String, val description: String, val sku: String,
    val instructor: String = "", val difficulty: Int = 0, val durationSeconds: Double = 0.0,
    val coverUrl: String? = null, val confirmedPurchases: Int? = null, val serverPriceToman: Long? = null,
    val compareAtToman: Long? = null, val discountEndsAtMillis: Long? = null, val difficultyLabel: String = "",
    val salesPaused: Boolean = false, val instructorProfile: InstructorProfile? = null)
data class Lesson(val id: String, val courseId: String, val section: String, val title: String,
    val version: Int, val bytes: Long, val sha256: String, val difficulty: Int = 0,
    val durationSeconds: Double = 0.0, val coverUrl: String? = null, val description: String = "",
    val isPreview: Boolean = false, val previewUrl: String? = null, val difficultyLabel: String = "", val subtitle: LessonSubtitle? = null)

/** Numeric identities remain stable; older APIs/caches still have readable badges. */
object DifficultyLevel {
    private val defaults = listOf("مقدماتی", "آسان", "متوسط", "پیشرفته", "حرفه‌ای",
        "چالش‌برانگیز", "دشوار", "بسیار دشوار", "تخصصی", "فوق‌تخصصی")
    private val emojis = listOf("🌱", "🙂", "💡", "🚀", "🔥", "🎯", "🧩", "⚡", "🏆", "💎")
    fun label(level: Int, custom: String = ""): String {
        if (level !in 1..10) return ""
        val title = custom.trim()
        return title.takeIf { it.codePointCount(0, it.length) in 1..40 && it != "null" && it.none { c -> c.isISOControl() || c == '<' || c == '>' } }
            ?: defaults[level - 1]
    }
    fun emoji(level: Int): String = emojis.getOrNull(level - 1).orEmpty()
}

// Do not use data classes for receipts/credentials: autogenerated toString must never leak secrets.
class Receipt(val sku: String, val token: String, val ownerUuid: String? = null)
class CourseAccess(val courseId: String, val token: String, val expiresAtMillis: Long, val ownerUuid: String? = null)
class CourseFailure(val userMessage: String, val status: Int = 0, val code: String = "", val operation: String = "", val retryAfterSeconds: Long? = null) : Exception(userMessage)

interface BillingGateway {
    val provider: String
    suspend fun owned(sku: String): Receipt?
    suspend fun purchase(sku: String): Receipt
    fun close()
}

interface PurchaseBackend {
    suspend fun verify(course: Course, provider: String, receipt: Receipt, restore: Boolean): CourseAccess
    suspend fun retryPending(course: Course, provider: String, receipt: Receipt, explicitRestore: Boolean): CourseAccess = verify(course, provider, receipt, true)
    suspend fun reconcile(course: Course, provider: String, receipt: Receipt): CourseAccess = verify(course, provider, receipt, true)
}

interface ReceiptStore {
    fun saveReceipt(courseId: String, receipt: Receipt)
    fun savePendingReceipt(course: Course, provider: String, receipt: Receipt) = saveReceipt(course.id, receipt)
    fun saveDiscoveredReceipt(course: Course, provider: String, receipt: Receipt) = savePendingReceipt(course, provider, receipt)
    fun requiresStoreRediscovery(courseId: String): Boolean = false
    fun receipt(courseId: String): Receipt?
    fun hasPendingReceipt(courseId: String): Boolean = false
    fun saveAccess(access: CourseAccess)
}

/** A failed inventory query must NEVER be interpreted as "not owned" and trigger a new purchase. */
class BuyCourse(private val backend: PurchaseBackend, private val receipts: ReceiptStore, private val inventoryTimeoutMs: Long = 30_000,
    private val onTiming: (String, Long) -> Unit = { _, _ -> }) {
    private suspend fun <T> timed(stage: String, block: suspend () -> T): T {
        val started = System.nanoTime()
        try { return block() } finally { onTiming(stage, (System.nanoTime() - started) / 1_000_000) }
    }
    /** Inventory discovery only. Empty results and SDK outages can never start payment or revoke an account purchase. */
    suspend fun reconcile(course: Course, billing: BillingGateway): CourseAccess? {
        if (receipts.hasPendingReceipt(course.id) && !receipts.requiresStoreRediscovery(course.id)) {
            val receipt = receipts.receipt(course.id)?.takeIf { it.sku == course.sku && it.token.isNotBlank() }
                ?: throw CourseFailure("رسید با دوره مطابقت ندارد.")
            return timed("pending_confirmation") { backend.retryPending(course, billing.provider, receipt, false) }.also {
                if (it.courseId != course.id) throw CourseFailure("دسترسی برگشتی با دوره مطابقت ندارد.")
                receipts.saveAccess(it)
            }
        }
        val receipt = timed("store_inventory") { kotlinx.coroutines.withTimeout(inventoryTimeoutMs) { billing.owned(course.sku) } } ?: return null
        if (receipt.sku != course.sku || receipt.token.isBlank()) throw CourseFailure("رسید با دوره مطابقت ندارد.")
        receipts.saveDiscoveredReceipt(course, billing.provider, receipt)
        return timed("receipt_confirmation") { backend.reconcile(course, billing.provider, receipt) }.also {
            if (it.courseId != course.id) throw CourseFailure("دسترسی برگشتی با دوره مطابقت ندارد.")
            receipts.saveAccess(it)
        }
    }

    suspend fun execute(course: Course, billing: BillingGateway, restoreOnly: Boolean): CourseAccess {
        // A paid receipt waiting for confirmation must never open payment again, even if inventory is down.
        if (receipts.hasPendingReceipt(course.id) && (!restoreOnly || !receipts.requiresStoreRediscovery(course.id))) {
            val pending = receipts.receipt(course.id)?.takeIf { it.sku == course.sku && it.token.isNotBlank() }
                ?: throw CourseFailure("رسید در انتظار با دوره مطابقت ندارد؛ با پشتیبانی تماس بگیر.")
            val access = timed("pending_confirmation") { backend.retryPending(course, billing.provider, pending, restoreOnly) }
            if (access.courseId != course.id) throw CourseFailure("دسترسی برگشتی با دوره مطابقت ندارد.")
            receipts.saveAccess(access)
            return access
        }
        val previous = timed("store_inventory") { kotlinx.coroutines.withTimeout(inventoryTimeoutMs) { billing.owned(course.sku) } }
        // A successfully queried but empty inventory must not discard an already-paid local receipt.
        // Only explicit restoration uses this fallback; every receipt is still verified by the server.
        val saved = if (restoreOnly && previous == null) receipts.receipt(course.id)?.takeIf { it.sku == course.sku && it.token.isNotBlank() } else null
        val receipt = previous ?: saved ?: if (restoreOnly) {
            throw CourseFailure("خرید قبلی این دوره در حساب فعلی استور پیدا نشد.", code = "not_owned")
        } else {
            if (course.salesPaused) throw CourseFailure("در حال حاضر فروش متوقف شده است.", code = "sales_paused")
            billing.purchase(course.sku)
        }
        if (receipt.sku != course.sku || receipt.token.isBlank()) throw CourseFailure("رسید خرید با دوره مطابقت ندارد.")
        // Persist before HTTP verification: process death/outage must not lose the paid receipt.
        if (restoreOnly && previous != null) receipts.saveDiscoveredReceipt(course, billing.provider, receipt)
        else receipts.savePendingReceipt(course, billing.provider, receipt)
        // Explicit restore authorizes recovery; merely discovering an old purchase during a buy does not.
        val access = timed("receipt_confirmation") {
            if (restoreOnly) backend.retryPending(course, billing.provider, receipt, true)
            else backend.verify(course, billing.provider, receipt, previous != null)
        }
        if (access.courseId != course.id) throw CourseFailure("دسترسی برگشتی با دوره مطابقت ندارد.")
        receipts.saveAccess(access)
        return access
    }
}

object CoursePolicy {
    fun discountVisible(course: Course, now: Long): Boolean = course.serverPriceToman != null &&
        course.compareAtToman != null && course.compareAtToman > course.serverPriceToman &&
        (course.discountEndsAtMillis == null || now < course.discountEndsAtMillis)
    fun serverPrice(sku: String, priceSku: String?, amount: Any?): Long? {
        if (priceSku == null) return null
        require(priceSku == sku)
        if (amount == null) return null
        val value = when (amount) { is Long -> amount; is Int -> amount.toLong(); else -> throw IllegalArgumentException("Invalid server price") }
        require(value in 0..1_000_000_000_000L)
        return value
    }
    fun purchaseNetworkAvailable(internet: Boolean, validated: Boolean) = internet && validated
    fun canLearn(lesson: Lesson, purchased: Boolean) = lesson.isPreview || purchased
    fun previewUrl(base: String, lesson: Lesson): String {
        require(lesson.isPreview)
        val url = requireNotNull(lesson.previewUrl)
        require(sameOrigin(base, url))
        val target = URI(url)
        val publicPrefix = URI(base.trimEnd('/')).path + "/public-video/${uuid(lesson.id)}/"
        if (target.path.startsWith(publicPrefix)) {
            require(target.fragment == null && target.rawQuery == null)
            uuid(target.path.removePrefix(publicPrefix))
            return url
        }
        val prefix = URI(base.trimEnd('/')).path + "/lessons/${uuid(lesson.id)}/video/"
        require(target.fragment == null && target.path.startsWith(prefix))
        uuid(target.path.removePrefix(prefix))
        require(!target.rawQuery.isNullOrBlank())
        return url
    }
    fun revokesAccess(code: String) = code in setOf("refunded", "rejected", "not_owned", "access_disabled")
    fun uuid(value: String): String {
        require(UUID.fromString(value).toString().equals(value, ignoreCase = true))
        return value.lowercase()
    }
    fun downloadKey(lesson: Lesson): String {
        require(lesson.version >= 0 && lesson.bytes in 1..(1024L * 1024 * 1024))
        require(lesson.sha256.matches(Regex("[a-fA-F0-9]{64}")))
        return "${uuid(lesson.id)}-${lesson.version}-${lesson.sha256.lowercase()}.mp4"
    }
    fun sameOrigin(base: String, candidate: String): Boolean = runCatching {
        val a = URI(base)
        val b = URI(candidate)
        b.scheme == "https" && a.host == b.host && b.userInfo == null && (b.port == -1 || b.port == 443)
    }.getOrDefault(false)
}
